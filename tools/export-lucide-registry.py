#!/usr/bin/env python3
"""Freeze the Lucide icon catalogue from a downloaded lucide npm package.

The pages generated by UIBench render icons through the Lucide CDN build,
whose lookup accepts both canonical icon names and deprecated aliases. This
tool copies those names out of one pinned package version so validation and
coverage audits work offline, exactly like ``export-symbol-registry.py`` does
for the HarmonyOS SDK. Obtain the package once with::

    npm pack lucide@<version> && tar -xzf lucide-<version>.tgz

then point ``--package`` at the extracted ``package/`` directory. Only the
frozen JSON is checked in; the tarball is not vendored.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from uibench.arkui.symbols import (  # noqa: E402
    LUCIDE_NAME_RE,
    LUCIDE_REGISTRY_FILE,
    LUCIDE_REGISTRY_VERSION,
    lucide_pascal_name,
)

ICONS_DIR = Path("dist/esm/icons")
ALIASES_FILE = Path("dist/esm/iconsAndAliases.mjs")
_EXPORT_LINE_RE = re.compile(
    r"^export \{ (?P<exports>[^}]+) \} from '\./icons/(?P<base>[a-z0-9-]+)\.mjs';$"
)
_EXPORT_NAME_RE = re.compile(r"default as ([A-Za-z0-9]+)")
# The CDN build folds ``data-lucide`` via toPascalCase, which is the only
# unambiguous direction (``clock-10`` vs ``arrow-down-0-1``). Canonical names
# are therefore verified in PascalCase space; alias display spellings are
# derived and must fold back onto their export name exactly.
_ACRONYM_BOUNDARY_RE = re.compile(r"([A-Z]+)([A-Z][a-z])")
_CAMEL_BOUNDARY_RE = re.compile(r"([a-z0-9])([A-Z])")
_LETTER_DIGIT_BOUNDARY_RE = re.compile(r"([A-Za-z])([0-9])")


def _pascal_to_display_kebab(name: str) -> str:
    value = _ACRONYM_BOUNDARY_RE.sub(r"\1-\2", name)
    value = _CAMEL_BOUNDARY_RE.sub(r"\1-\2", value)
    value = _LETTER_DIGIT_BOUNDARY_RE.sub(r"\1-\2", value)
    return value.lower()


def _atomic_write(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        # mkstemp is 0600; the registry is checked in and read like any source.
        os.chmod(temporary, 0o644)
        os.replace(temporary, path)
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise


def _package_provenance(package: Path) -> dict[str, object]:
    manifest_file = package / "package.json"
    if not manifest_file.is_file():
        raise FileNotFoundError(f"required package file is missing: {manifest_file}")
    with manifest_file.open("r", encoding="utf-8") as stream:
        manifest = json.load(stream)
    if not isinstance(manifest, dict) or manifest.get("name") != "lucide":
        raise ValueError(
            f"{manifest_file} does not describe the 'lucide' package; "
            "point --package at the extracted npm package root"
        )
    version = str(manifest.get("version") or "").strip()
    if not version:
        raise ValueError("lucide package.json has no version")
    return {
        "package": "lucide",
        "version": version,
        "iconsDir": ICONS_DIR.as_posix(),
        "aliasesFile": ALIASES_FILE.as_posix(),
    }


def _extract_icons(package: Path) -> tuple[str, ...]:
    icons_dir = package / ICONS_DIR
    if not icons_dir.is_dir():
        raise FileNotFoundError(f"required icon directory is missing: {icons_dir}")
    names: set[str] = set()
    for entry in icons_dir.iterdir():
        if entry.suffix != ".mjs" or entry.name.endswith(".mjs.map"):
            continue
        name = entry.name[: -len(".mjs")]
        if not LUCIDE_NAME_RE.fullmatch(name):
            raise ValueError(
                f"lucide icon file {entry.name!r} is not in canonical "
                "kebab-case form; the parsing rule needs to be revisited"
            )
        names.add(name)
    if not names:
        raise ValueError(f"{icons_dir} contained no icon modules")
    return tuple(sorted(names))


def _extract_aliases(package: Path, icons: tuple[str, ...]) -> dict[str, str]:
    """Read alias exports and verify every derived spelling in Pascal space."""
    aliases_file = package / ALIASES_FILE
    if not aliases_file.is_file():
        raise FileNotFoundError(f"required alias manifest is missing: {aliases_file}")
    icon_set = set(icons)
    seen_bases: set[str] = set()
    pascal_owners = {lucide_pascal_name(icon): icon for icon in icons}
    if len(pascal_owners) != len(icon_set):
        raise ValueError("canonical icon names collide in PascalCase space")
    aliases: dict[str, str] = {}
    for line in aliases_file.read_text(encoding="utf-8").splitlines():
        match = _EXPORT_LINE_RE.fullmatch(line.strip())
        if match is None:
            continue
        base = match.group("base")
        if base not in icon_set:
            raise ValueError(
                f"iconsAndAliases exports unknown icon module {base!r}"
            )
        seen_bases.add(base)
        export_names = _EXPORT_NAME_RE.findall(match.group("exports"))
        if not export_names:
            raise ValueError(f"could not parse export names in line: {line!r}")
        base_pascal = lucide_pascal_name(base)
        if base_pascal not in export_names:
            raise ValueError(
                f"{base!r} has no export named {base_pascal!r} "
                f"(got {export_names!r}); the folding rule needs revisiting"
            )
        for export_name in export_names:
            if export_name == base_pascal:
                continue
            display = _pascal_to_display_kebab(export_name)
            if not LUCIDE_NAME_RE.fullmatch(display):
                raise ValueError(
                    f"alias {export_name!r} has no kebab display form"
                )
            if lucide_pascal_name(display) != export_name:
                raise ValueError(
                    f"alias display {display!r} does not fold back onto "
                    f"{export_name!r}; the conversion rule needs revisiting"
                )
            owner = pascal_owners.get(export_name)
            if owner is not None:
                raise ValueError(
                    f"alias {export_name!r} for {base!r} collides with the "
                    f"canonical icon {owner!r} in lookup space"
                )
            previous = aliases.get(display)
            if previous is not None and previous != base:
                raise ValueError(
                    f"alias {display!r} maps to both {previous!r} and {base!r}"
                )
            pascal_owners[export_name] = base
            aliases[display] = base
    missing = icon_set - seen_bases
    if missing:
        raise ValueError(
            "iconsAndAliases does not export every icon module; missing: "
            + ", ".join(sorted(missing)[:5])
        )
    return dict(sorted(aliases.items()))


def export_lucide_registry(
    package: Path,
    output: Path = LUCIDE_REGISTRY_FILE,
) -> dict[str, object]:
    package = package.resolve()
    if not package.is_dir():
        raise NotADirectoryError(f"lucide package not found at {package}")
    icons = _extract_icons(package)
    aliases = _extract_aliases(package, icons)
    registry = {
        "kind": "uibench-lucide-icon-registry",
        "registryVersion": LUCIDE_REGISTRY_VERSION,
        "source": _package_provenance(package),
        "aliases": aliases,
        "icons": list(icons),
    }
    _atomic_write(
        output,
        (json.dumps(registry, ensure_ascii=False, indent=2) + "\n").encode("utf-8"),
    )
    return {
        "ok": True,
        "output": str(output),
        "icons": len(icons),
        "aliases": len(aliases),
        "source": registry["source"],
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Freeze the Lucide icon names one npm package version renders into "
            "the repository so mapping validation and audits work offline."
        ),
    )
    parser.add_argument(
        "--package",
        required=True,
        type=Path,
        metavar="DIR",
        help="extracted lucide npm package root (the directory with package.json)",
    )
    parser.add_argument(
        "--out",
        default=LUCIDE_REGISTRY_FILE,
        type=Path,
        metavar="FILE",
        help="registry file to write (default: %(default)s)",
    )
    args = parser.parse_args()
    result = export_lucide_registry(args.package, args.out)
    print(json.dumps(result, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
